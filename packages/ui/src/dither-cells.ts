// the ordered dither behind everything that fades through a pattern: the photo-fill mask, the colour veil over
// photographs, the carousel dissolve and the tone a pressed control takes. one matrix and one cell size keep the grain identical.

export const ditherCellSizePx = 2;
export const bayerPattern: readonly (readonly number[])[] = [
  [0, 8, 2, 10],
  [12, 4, 14, 6],
  [3, 11, 1, 9],
  [15, 7, 13, 5],
];
export const bayerSideLength = bayerPattern.length;
export const ditherLevelCount = bayerSideLength * bayerSideLength;
export const ditherTileSizePx = bayerSideLength * ditherCellSizePx;

export interface DitherCell {
  readonly threshold: number;
  readonly columnIndex: number;
  readonly rowIndex: number;
}

const quarterToneLevel = ditherLevelCount / 4;
const halfToneLevel = ditherLevelCount / 2;
const quarterToneOpacity = 0.22;
const halfToneOpacity = 0.3;
// a browser drops a mask whose every layer has collapsed, which would show a surface that should be hidden.
const emptyMaskLayer = "linear-gradient(transparent, transparent)";

/** Every cell of the tile, ordered by the threshold at which it switches on. */
export function ditherCells(): readonly DitherCell[] {
  return bayerPattern
    .flatMap((thresholds, rowIndex) => thresholds.map((threshold, columnIndex) => ({ threshold, columnIndex, rowIndex })))
    .sort((left, right) => left.threshold - right.threshold);
}

function cellPath({ columnIndex, rowIndex }: DitherCell): string {
  return `M${columnIndex * ditherCellSizePx} ${rowIndex * ditherCellSizePx}h${ditherCellSizePx}v${ditherCellSizePx}h-${ditherCellSizePx}z`;
}

function tileUrl(path: string, pathAttributes = ""): string {
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' width='${ditherTileSizePx}' height='${ditherTileSizePx}' viewBox='0 0 ${ditherTileSizePx} ${ditherTileSizePx}' shape-rendering='crispEdges'><path ${pathAttributes}d='${path}'/></svg>`;
  return `url("data:image/svg+xml,${svg.replaceAll("<", "%3C").replaceAll(">", "%3E").replaceAll("#", "%23")}")`;
}

function toneUrl(level: number, opacity: number): string {
  const path = ditherCells().filter(({ threshold }) => threshold < level).map(cellPath).join("");
  return tileUrl(path, `fill='%23fff' fill-opacity='${opacity}' `);
}

/** One mask layer per threshold, so the nth layer is the nth cell to switch on. */
export function ditherMaskLayers(): readonly string[] {
  return [...ditherCells().map((cell) => tileUrl(cellPath(cell))), emptyMaskLayer];
}

/** A layer is drawn at tile size once the level passes its threshold and collapses to nothing below it. */
export function ditherMaskSizes(): readonly string[] {
  return [...ditherCells().map(({ threshold }) => `calc(${ditherTileSizePx}px * clamp(0, var(--dither-level, ${ditherLevelCount}) - ${threshold}, 1))`), "auto"];
}

/** The stylesheet written to styles/dither.css by scripts/generate-dither-cells.mjs. */
export function ditherStylesheet(): string {
  return [
    "/* generated by scripts/generate-dither-cells.mjs from packages/ui/src/dither-cells.ts. do not edit by hand. */",
    "",
    `/* how much of a surface the dither mask lets through, from 0 (nothing) to ${ditherLevelCount} (all of it).`,
    "   the integer type means a linear transition lands on whole thresholds and never on a blend between two. */",
    `@property --dither-level { syntax: "<integer>"; inherits: false; initial-value: ${ditherLevelCount}; }`,
    "",
    ":root {",
    `  --dither-cells: ${ditherMaskLayers().join(", ")};`,
    "  /* the tone a pressed surface takes: a quarter of the cells for rows and cards, half for labels and controls. */",
    `  --dither-quarter-tone: ${toneUrl(quarterToneLevel, quarterToneOpacity)};`,
    `  --dither-half-tone: ${toneUrl(halfToneLevel, halfToneOpacity)};`,
    "}",
    "",
    "/* .dither-resolve cuts the element itself; .dither-veil cuts a layer laid over it. both are driven by --dither-level. */",
    ".dither-resolve, .dither-veil::before {",
    "  mask-image: var(--dither-cells);",
    `  mask-size: ${ditherMaskSizes().join(", ")};`,
    "  mask-repeat: repeat;",
    "}",
    "",
    "/* starts one threshold in, so the first cells change the instant a photograph is selected. */",
    `@keyframes dither-resolve { from { --dither-level: 1; } to { --dither-level: ${ditherLevelCount}; } }`,
    "",
  ].join("\n");
}
